#!/usr/bin/env node
/** Local browser smoke for the fictional prototype. Does not replace human CT-02. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CC01_PLAYWRIGHT_MODULE || '@playwright/test');
const browser = await chromium.launch({ headless: true, ...(process.env.CC01_CHROMIUM_EXECUTABLE ? { executablePath: process.env.CC01_CHROMIUM_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], network = [], scenarios = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
const evidence = process.env.CC01_EVIDENCE_DIR;
if (evidence) await mkdir(evidence, { recursive: true });
const state = async expected => assert.equal(await page.locator('#status').innerText(), expected);
const selectProfile = value => page.selectOption('#profile', value);
const noOverflow = async () => assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal page overflow');
try {
  await page.goto(new URL('../../docs/central-chamados/cc-01/prototype.html', import.meta.url).href);
  for (const scenario of ['question', 'incident']) {
    await page.selectOption('#scenario', scenario);
    await selectProfile('requester');
    await state('Novo');
    assert.equal(await page.locator('#triage').count(), 0, 'Requester cannot triage');
    assert((await page.locator('#owner').innerText()).length > 0);
    assert((await page.locator('#nextStep').innerText()).length > 0);
    if (await page.locator('#expectedToggle').getAttribute('aria-expanded') === 'false') await page.locator('#expectedToggle').click();
    assert(await page.locator('#expected').isVisible());
    await selectProfile('agent');
    await page.locator('#triageReason').fill('');
    await page.locator('#triage').click();
    await state('Novo');
    await page.locator('#triageReason').fill('Impacto e urgência revisados no cenário fictício.');
    await page.locator('#triage').click();
    await state('Aberto');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'subject', 'Focus follows the next stage');
    await page.locator('#assign').click();
    await state('Em andamento');
    await page.locator('#wait').click();
    await state('Em andamento');
    assert(await page.locator('#toReview').isDisabled());
    await page.locator('#wait').click();
    await page.locator('#changeButton').click();
    await page.selectOption('#changeType', scenario === 'question' ? 'technical_cr' : 'general_change');
    await page.locator('#linkChange').click();
    assert((await page.locator('#changeContent').innerText()).includes('Em revisão'));
    assert.equal(await page.locator('#saveReview').count(), 0, 'Linking a change does not grant review');
    await page.locator('[data-close="changeDialog"]').click();
    await selectProfile('reviewer');
    await page.locator('#changeButton').click();
    await page.locator('#saveReview').click();
    assert((await page.locator('#changeContent').innerText()).includes('Em revisão'));
    await page.locator('[data-close="changeDialog"]').click();
    await selectProfile('agent');
    await page.locator('#toReview').click();
    await state('Em revisão');
    assert(await page.locator('#closeTicket').isDisabled());
    await selectProfile('requester');
    await page.locator('#notResolved').click();
    await state('Em andamento');
    await selectProfile('agent');
    await page.locator('#toReview').click();
    await selectProfile('requester');
    await page.locator('#confirm').click();
    await selectProfile('agent');
    await page.locator('#closure').fill('');
    await page.locator('#closeTicket').click();
    await state('Em revisão');
    await page.locator('#closure').fill('Resultado fictício verificado.');
    await page.locator('#closeTicket').click();
    await state('Concluído');
    assert((await page.locator('#changeSummary').innerText()).includes('Em revisão'), 'Ticket closure must not approve a linked change');
    await noOverflow();
    if (evidence) await page.screenshot({ path: resolve(evidence, `${scenario}-desktop.png`), fullPage: true });
    await selectProfile('requester');
    await page.locator('#reopen').click();
    await state('Concluído');
    await page.locator('#reopenReason').fill('O mesmo problema voltou na simulação.');
    await page.locator('#reopen').click();
    await state('Aberto');
    assert.equal(await page.locator('#cycle').innerText(), 'Ciclo 2');
    assert((await page.locator('#changeSummary').innerText()).includes('Em revisão'));
    scenarios.push({ scenario, result: 'passed', closureDoesNotApproveChange: true, reopeningPreservesHistory: true });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.selectOption('#scenario', 'incident');
  await selectProfile('agent');
  await noOverflow();
  if (evidence) await page.screenshot({ path: resolve(evidence, 'incident-mobile.png'), fullPage: true });
  await page.locator('#nextHelp').click();
  assert(await page.locator('#helpDialog').isVisible());
  await page.keyboard.press('Escape');
  assert(!(await page.locator('#helpDialog').isVisible()));
  assert.deepEqual(errors, []);
  assert.deepEqual(network, []);
  console.log(JSON.stringify({ type: 'automated_prototype_smoke', executedAt: new Date().toISOString(), browser: await browser.version(), scenarios, mobileViewport: '390x844', desktopViewport: '1440x1000', externalRequests: network.length, pageErrors: errors.length, ct02HumanAcceptance: 'pending' }, null, 2));
} finally {
  await browser.close();
}
